// Builds passages.js from data.js and the Berean Standard Bible (scripts/bsb.json).
//   node scripts/build.js            build passages.js and check every reference and phrase
//   node scripts/build.js --review   also print every list with its text, for proofreading
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const BSB = require("./bsb.json");
const { BOOKS, expand } = require("./refs.js");

const root = path.join(__dirname, "..");
const ctx = {};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, "data.js"), "utf8") +
  "\nthis.D={CORE,CORE_PHASES,COMMISSION,TIMELINE,EVENT_TYPES,KINDS,CHURCHES,GROUPS,ELEMENTS,START,PLANTING,MARKS,STORY,LEADERS,HANDOFFS,MATURITY};", ctx);
const D = ctx.D;

const errors = [];
const passages = {};
const has = k => k in BSB && BSB[k].trim() !== "";

function add(ref) {
  if (passages[ref]) return passages[ref];
  try {
    const { book, verses } = expand(ref, has);
    passages[ref] = { book, verses: verses.map(x => [x.c, x.v, BSB[x.key].trim()]) };
    return passages[ref];
  } catch (e) { errors.push(e.message); return null; }
}

// Collect every reference.
const lists = []; // [title, refs] for review
D.CHURCHES.forEach(([id, name, , secs]) => Object.entries(secs).forEach(([k, refs]) => {
  if (!D.KINDS.some(x => x[0] === k)) errors.push(`Unknown section "${k}" in ${id}`);
  refs.forEach(add); lists.push([`${name} · ${k}`, refs]);
}));
const ids = new Set(D.CHURCHES.map(c => c[0]));
D.GROUPS.forEach(g => g[2].forEach(id => ids.has(id) || errors.push(`Unknown church "${id}" in group`)));
D.START.forEach(([id, cells]) => {
  if (!ids.has(id)) errors.push(`Unknown church "${id}" in START`);
  Object.entries(cells).forEach(([k, ref]) => {
    if (!D.ELEMENTS.some(e => e[0] === k)) errors.push(`Unknown element "${k}"`);
    add(ref); lists.push([`START ${id} · ${k}`, [ref]]);
  });
});

const norm = s => s.toLowerCase().replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/[^a-z0-9' ]+/g, " ").replace(/\s+/g, " ").trim();
function phrased(name, rows) {
  rows.forEach(([phrase, pref, refs]) => {
    const p = add(pref);
    if (p) {
      const text = norm(p.verses.map(v => v[2]).join(" "));
      const parts = phrase.split("…").map(norm).filter(Boolean);
      let at = 0;
      for (const part of parts) {
        const i = text.indexOf(part, at);
        if (i < 0) { errors.push(`${name}: "${phrase}" is not in ${pref}`); break; }
        at = i + part.length;
      }
    }
    refs.forEach(add);
    lists.push([`${name}: “${phrase}” (${pref})`, refs]);
  });
}
phrased("PLANTING", D.PLANTING);
phrased("MARKS", D.MARKS);
phrased("STORY", D.STORY);
phrased("LEADERS", D.LEADERS);
phrased("MATURITY", D.MATURITY);
D.HANDOFFS.forEach(([who, refs]) => { refs.forEach(add); lists.push([`HANDOFF ${who}`, refs]); });
D.COMMISSION.forEach(([head, phrase, pref, refs]) => phrased("COMMISSION", [[phrase, pref, refs]]));
const TYPES = new Set(D.EVENT_TYPES.map(t => t[0]));
Object.entries(D.TIMELINE).forEach(([id, evs]) => {
  if (!ids.has(id)) errors.push(`Unknown church "${id}" in TIMELINE`);
  evs.forEach(([y, t, label, ref, quote]) => {
    if (!TYPES.has(t)) errors.push(`Unknown event type "${t}" in ${id}`);
    const p = add(ref);
    if (p && !norm(p.verses.map(v => v[2]).join(" ")).includes(norm(quote))) errors.push(`TIMELINE ${id}: "${quote}" is not in ${ref}`);
    lists.push([`TIMELINE ${id} ${y} ${label}`, [ref]]);
  });
});
D.CHURCHES.forEach(c => D.TIMELINE[c[0]] || errors.push(`No timeline for ${c[0]}`));
D.CORE.forEach(([name, phrase, pref, sum, refs, pages, els]) => {
  phrased("CORE", [[phrase, pref, refs]]);
  els.forEach(k => D.ELEMENTS.some(e => e[0] === k) || errors.push(`CORE ${name}: unknown element ${k}`));
  pages.forEach(pg => { const [k, n] = pg.split("-");
    const rows = { mark: D.MARKS, stage: D.PLANTING }[k];
    if (rows ? !rows[+n] : !["leaders", "handoffs", "commission", "timeline"].includes(pg)) errors.push(`CORE ${name}: unknown page ${pg}`); });
});
// Every mark and planting stage should belong to some core element.
D.MARKS.forEach((m, i) => D.CORE.some(c => c[5].includes(`mark-${i}`)) || errors.push(`Mark ${i} "${m[0]}" is in no core element`));
D.PLANTING.forEach((m, i) => D.CORE.some(c => c[5].includes(`stage-${i}`)) || errors.push(`Stage ${i} "${m[0]}" is in no core element`));



if (errors.length) { console.error([...new Set(errors)].join("\n")); process.exit(1); }

// Write passages.js: { reference: [book index, [[chapter, verse, text], ...]] }, in canonical order.
const order = r => { const p = passages[r]; return p.book * 1e6 + p.verses[0][0] * 1e3 + p.verses[0][1]; };
const refs = Object.keys(passages).sort((a, b) => order(a) - order(b) || a.length - b.length);
const out = "// Generated by scripts/build.js from data.js and the Berean Standard Bible. Do not edit.\n" +
  "// The Holy Bible, Berean Standard Bible, BSB. Public domain.\n" +
  "const BOOK_NAMES = " + JSON.stringify(BOOKS.map(b => b[0])) + ";\n" +
  "const PASSAGES = {\n" + refs.map(r => `${JSON.stringify(r)}:[${passages[r].book},${JSON.stringify(passages[r].verses)}]`).join(",\n") + "\n};\n";
fs.writeFileSync(path.join(root, "passages.js"), out);
const verseCount = new Set(refs.flatMap(r => passages[r].verses.map(v => passages[r].book + "." + v[0] + "." + v[1]))).size;
console.log(`passages.js: ${refs.length} passages, ${verseCount} distinct verses.`);

if (process.argv.includes("--review")) {
  for (const [title, rs] of lists) {
    console.log("\n## " + title);
    for (const r of rs) console.log(`- ${r}: ${passages[r].verses.map(v => v[2]).join(" ")}`);
  }
}
